create function private.audit_change() returns trigger language plpgsql security definer set search_path='' as $$
begin
 insert into public.audit_logs(actor,entity,entity_key,operation) values(auth.jwt()->>'sub',tg_table_name,coalesce(to_jsonb(new)->>'id',to_jsonb(new)->>'slug',to_jsonb(new)->>'key',to_jsonb(old)->>'id',to_jsonb(old)->>'slug',to_jsonb(old)->>'key'),tg_op);
 return coalesce(new,old);
end;$$;
create function private.stock_audit() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.stock<>old.stock or new.reserved<>old.reserved then
 insert into public.inventory_movements(product_id,variant_id,stock_delta,reserved_delta,actor) values(new.product_id,new.id,new.stock-old.stock,new.reserved-old.reserved,auth.jwt()->>'sub');
 end if;return new;
end;$$;
create trigger variant_stock_audit after update on public.product_variants for each row execute function private.stock_audit();
create function public.media_visible(asset uuid) returns boolean language sql stable security definer set search_path='' as $$
 select public.has_permission('catalog') or public.has_permission('content') or exists(
 select 1 from public.product_media m join public.products p on p.id=m.product_id where m.asset_id=asset and p.publication='published'
 ) or exists(select 1 from public.collections c where c.publication='published' and c.data->>'image'='/api/media/'||asset::text)
 or exists(select 1 from public.website_content c where c.publication='published' and strpos(c.data::text,'/api/media/'||asset::text)>0);
$$;
