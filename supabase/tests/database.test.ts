import test from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {readFile,readdir} from 'node:fs/promises';

test('fresh migrations, RLS ownership, admin isolation and transactional inventory',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create role service_role bypassrls; create schema auth; create schema storage;
 create function auth.jwt() returns jsonb language sql stable as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
 grant usage on schema public,auth,storage to anon,authenticated,service_role; grant execute on function auth.jwt() to anon,authenticated,service_role;
 create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text); alter table storage.objects enable row level security; grant select,insert,delete on storage.objects to anon,authenticated;`);
 for(const f of (await readdir('supabase/migrations')).sort())await db.exec(await readFile('supabase/migrations/'+f,'utf8'));
 const as=async(role:string,id?:string)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({sub:id,role})]);await db.exec(`set role ${role}`);};
 const deny=async(sql:string)=>{await assert.rejects(db.exec(sql));};
 await as('authenticated','user_customer');
 assert.equal((await db.query<{has_permission:boolean}>("select public.has_permission('catalog')")).rows[0].has_permission,false);
 await deny("insert into public.admin_users values('user_customer','owner',true,now())");
 await deny("select public.save_content('hero','{}','published',0)");
 await db.exec("insert into public.customer_profiles(clerk_user_id) values('user_customer')");
 await deny("insert into public.customer_profiles(clerk_user_id) values('user_other')");
 await as('authenticated','user_other');
 assert.equal((await db.query('select * from public.customer_profiles')).rows.length,0);
 await db.exec('reset role');
 await db.exec("insert into public.admin_users(clerk_user_id,role) values('user_admin','owner')");
 await as('authenticated','user_admin');
 await db.exec("select public.save_content('checkout','{\"shippingPaise\":0}','published',0)");
 await db.exec(`select public.save_catalog_entry('collection','{"slug":"silk","name":"Silk","description":"Silk","image":"/images/demo.jpg","publication":"published"}',0,false)`);
 const product={id:'p1',slug:'sample',name:'Sample',price:100,publication:'published',featured:true,composition:'Silk',dimensions:'6m',care:['Dry clean'],collections:['silk'],images:[{src:'/images/demo.jpg',alt:'sample'}],variants:[{id:'v1',name:'Gold',hex:'#b59663',stock:2}]};
 await db.query("select public.save_catalog_entry('product',$1::jsonb,1,false)",[JSON.stringify(product)]);
 await db.query("select public.save_catalog_entry('product',$1::jsonb,2,false)",[JSON.stringify({...product,id:'p2',slug:'draft',publication:'draft'})]);
 await as('anon');assert.equal((await db.query('select * from public.products')).rows.length,1);
 await deny("select public.place_order('[]','{}','00000000-0000-4000-8000-000000000001',null)");
 await as('authenticated','user_customer');
 const args=[JSON.stringify([{productId:'p1',variantId:'v1',quantity:2}]),JSON.stringify({name:'Test',phone:'0000000000',street:'Test street',city:'Test',state:'Test',postalCode:'500001'}),'00000000-0000-4000-8000-000000000001'];
 const order=async()=>db.query<{id:string,total_paise:number,status:string}>('select * from public.place_order($1::jsonb,$2::jsonb,$3::uuid,null)',args);
 const o=(await order()).rows[0];assert.equal(Number(o.total_paise),20000);assert.equal(o.status,'pending_payment');assert.equal((await order()).rows[0].id,o.id);
 await deny(`update public.orders set status='paid' where id='${o.id}'`);
 await deny(`select public.confirm_verified_payment('${o.id}','test','fake',20000)`);
 await as('authenticated','user_other');assert.equal((await db.query('select * from public.orders')).rows.length,0);
 await deny(`select public.cancel_pending_order('${o.id}')`);
 await assert.rejects(db.query('select * from public.place_order($1::jsonb,$2::jsonb,$3::uuid,null)',[...args.slice(0,2),'00000000-0000-4000-8000-000000000002']));
 await as('authenticated','user_customer');await db.exec(`select public.cancel_pending_order('${o.id}')`);
 await as('authenticated','user_admin');assert.equal((await db.query<{reserved:number}>('select reserved from public.product_variants where product_id=\'p1\'')).rows[0].reserved,0);
 await deny("select public.save_content('checkout','{}','published',0)");
 await db.exec('reset role');
 const tables=await db.query<{relname:string,relrowsecurity:boolean}>("select relname,relrowsecurity from pg_class join pg_namespace n on n.oid=relnamespace where n.nspname='public' and relkind='r'");
 assert.ok(tables.rows.every(t=>t.relrowsecurity));
 await db.close();
});
